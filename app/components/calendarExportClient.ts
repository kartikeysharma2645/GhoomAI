/**
 * Client-side calendar export: generates a downloadable .ics (iCalendar) file
 * from a TripPlanData plan. Lightweight, dependency-free implementation.
 *
 * Only timed itinerary items (attractions and meals with startTime/endTime)
 * become VEVENT entries. Untimed items are omitted rather than fabricating
 * times.
 *
 * All output is derived from the plan's actual data — no place, time, or
 * price is invented.
 */

function icsEscape(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,");
}

function formatIcsDate(date: string): string {
  return date.replace(/-/g, "");
}

function formatIcsDateTime(date: string, time: string): string {
  const [hh, mm] = time.split(":").map(Number);
  const dt = new Date(Date.UTC(
    Number(date.slice(0, 4)),
    Number(date.slice(5, 7)) - 1,
    Number(date.slice(8, 10)),
    hh,
    mm,
  ));
  return dt.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
}

export function buildIcsContentClient(plan: {
  destination: string;
  days: Array<{
    dayNumber: number;
    date?: string;
    items: Array<{
      id: string;
      kind: string;
      title: string;
      startTime?: string;
      endTime?: string;
      place?: { name?: string; address?: string };
      notes?: string;
    }>;
  }>;
}): string {
  const lines: string[] = [];
  const now = new Date();
  const dtstamp = now.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");

  lines.push("BEGIN:VCALENDAR");
  lines.push("VERSION:2.0");
  lines.push("PRODID:-//GhoomAI//Itinerary Export//EN");
  lines.push(`X-WR-CALNAME:${icsEscape(`Trip to ${plan.destination}`)}`);
  lines.push(
    `X-WR-CALDESC:${icsEscape("Itinerary generated by GhoomAI — plan it, check it, experience it.")}`,
  );
  lines.push("CALSCALE:GREGORIAN");
  lines.push("METHOD:PUBLISH");

  for (const day of plan.days) {
    const dayDateStr = day.date;
    if (!dayDateStr) continue;

    for (const item of day.items) {
      if (item.kind !== "attraction" && item.kind !== "meal") continue;
      if (!item.startTime || !item.endTime) continue;

      const start = formatIcsDateTime(dayDateStr, item.startTime);
      const end = formatIcsDateTime(dayDateStr, item.endTime);
      const uid = `ghoomai-${plan.destination.replace(/[^a-z0-9]/gi, "-")}-${day.dayNumber}-${item.id}@ghoomai.local`;

      lines.push("BEGIN:VEVENT");
      lines.push(`UID:${icsEscape(uid)}`);
      lines.push(`DTSTAMP:${dtstamp}`);
      lines.push(`DTSTART:${start}`);
      lines.push(`DTEND:${end}`);
      lines.push(`SUMMARY:${icsEscape(item.title)}`);
      if (item.place?.name) {
        lines.push(
          `DESCRIPTION:${icsEscape(
            `${item.place.name}${item.place.address ? ` · ${item.place.address}` : ""}`,
          )}`,
        );
      }
      if (item.notes) {
        lines.push(`DESCRIPTION:${icsEscape(item.notes)}`);
      }
      lines.push("END:VEVENT");
    }
  }

  lines.push("END:VCALENDAR");
  return lines.join("\r\n");
}

export function icsFilenameClient(destination: string): string {
  const safe = destination
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);
  return `ghoomai-${safe}-itinerary.ics`;
}

/** Downloads the .ics content as a file. */
export function downloadIcs(content: string, filename: string): void {
  const blob = new Blob([content], { type: "text/calendar;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
