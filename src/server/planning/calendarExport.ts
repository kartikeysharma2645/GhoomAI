/**
 * Calendar export: generates a downloadable .ics (iCalendar) file from a
 * TripPlan. Lightweight, dependency-free implementation.
 *
 * Only timed itinerary items (attractions and meals with startTime/endTime)
 * become VEVENT entries. Untimed items (notes such as "Evening at leisure")
 * are represented as all-day events only when they carry a date; items
 * without any time information are omitted rather than fabricating times.
 *
 * All output is derived from the plan's actual data — no place, time, or
 * price is invented.
 */

import type { TripPlan } from "../trips/plan";

/** Escapes a string for use in an iCalendar property value. */
function icsEscape(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,");
}

/** Formats a YYYY-MM-DD date as an iCalendar DATE value (YYYYMMDD). */
function formatIcsDate(date: string): string {
  return date.replace(/-/g, "");
}

/** Formats a YYYY-MM-DD date and HH:MM time as an iCalendar DATETIME (UTC). */
function formatIcsDateTime(date: string, time: string): string {
  const [hh, mm] = time.split(":").map(Number);
  const dt = new Date(Date.UTC(
    Number(date.slice(0, 4)),
    Number(date.slice(5, 7)) - 1,
    Number(date.slice(8, 10)),
    hh,
    mm,
  ));
  return dt.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
}

/** Returns the date string for a trip day, or undefined when unavailable. */
function dayDate(day: { date?: string; dayNumber: number }): string | undefined {
  return day.date;
}

/** Builds the .ics file content from a TripPlan. */
export function buildIcsContent(plan: {
  destination: string;
  durationDays: number;
  days: Array<{
    dayNumber: number;
    date?: string;
    items: Array<{
      id: string;
      kind: string;
      title: string;
      startTime?: string;
      endTime?: string;
      place?: { name?: string; address?: string };
      notes?: string;
    }>;
  }>;
}): string {
  const lines: string[] = [];
  const now = new Date();
  const dtstamp = now.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");

  lines.push("BEGIN:VCALENDAR");
  lines.push("VERSION:2.0");
  lines.push("PRODID:-//GhoomAI//Itinerary Export//EN");
  lines.push(`X-WR-CALNAME:${icsEscape(`Trip to ${plan.destination}`)}`);
  lines.push(`X-WR-CALDESC:${icsEscape("Itinerary generated by GhoomAI — plan it, check it, experience it.")}`);
  lines.push("CALSCALE:GREGORIAN");
  lines.push("METHOD:PUBLISH");

  let eventCount = 0;

  for (const day of plan.days) {
    const dayDateStr = dayDate(day);
    const dayHasDate = !!dayDateStr;

    for (const item of day.items) {
      // Only timed items (attractions and meals) become timed events.
      if (item.kind !== "attraction" && item.kind !== "meal") continue;
      if (!item.startTime || !item.endTime) continue;
      if (!dayHasDate) continue;

      const start = formatIcsDateTime(dayDateStr!, item.startTime);
      const end = formatIcsDateTime(dayDateStr!, item.endTime);
      const uid = `ghoomai-${plan.destination.replace(/[^a-z0-9]/gi, "-")}-${day.dayNumber}-${item.id}@ghoomai.local`;

      lines.push("BEGIN:VEVENT");
      lines.push(`UID:${icsEscape(uid)}`);
      lines.push(`DTSTAMP:${dtstamp}`);
      lines.push(`DTSTART:${start}`);
      lines.push(`DTEND:${end}`);
      lines.push(`SUMMARY:${icsEscape(item.title)}`);
      if (item.place?.name) {
        lines.push(`DESCRIPTION:${icsEscape(`${item.place.name}${item.place.address ? ` · ${item.place.address}` : ""}`)}`);
      }
      if (item.notes) {
        lines.push(`DESCRIPTION:${icsEscape(item.notes)}`);
      }
      lines.push("END:VEVENT");
      eventCount += 1;
    }
  }

  lines.push("END:VCALENDAR");
  return lines.join("\r\n");
}

/** Generates a sensible filename for the export. */
export function icsFilename(destination: string): string {
  const safe = destination
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);
  return `ghoomai-${safe}-itinerary.ics`;
}
